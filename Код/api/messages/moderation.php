<?php

/**
 * Базовая модерация текста личных сообщений между игроками: замена мата
 * и грубых оскорблений на вежливые аналоги. Не блокирует отправку —
 * просто подменяет отдельные слова, чтобы не считывать намерение или
 * контекст (это не полноценный анти-мат движок, а мягкий фильтр).
 *
 * Работает по границам слов (с учётом русских окончаний через \S*),
 * регистронезависимо, сохраняя первую букву регистра результата.
 */

/**
 * Список замен: ключ — корень/грубое слово (регулярка без разделителей),
 * значение — вежливый аналог. Порядок важен: более длинные/специфичные
 * паттерны должны идти раньше более общих, если могут пересекаться.
 */
function bober_moderation_word_map()
{
    return [
        'бляд\S*' => 'блин',
        'бля' => 'блин',
        'сук[аи]\S*' => 'вот незадача',
        'хуй\S*' => 'ерунда',
        'хуе\S*' => 'ерунда',
        'хуё\S*' => 'ерунда',
        'пизд\S*' => 'фигня',
        'еба\S*' => 'блин',
        'ёб\S*' => 'блин',
        'выеб\S*' => 'обыграл',
        'долбо[её]б\S*' => 'чудак',
        'мудак\S*' => 'вредина',
        'муд[ои]л\S*' => 'вредина',
        'гандон\S*' => 'вредина',
        'ублюдок\S*' => 'негодник',
        'ублюдк\S*' => 'негодник',
        'уёб\S*' => 'негодник',
        'скотин\S*' => 'вредина',
        'сволоч\S*' => 'вредина',
        'дебил\S*' => 'чудак',
        'идиот\S*' => 'чудак',
        'кретин\S*' => 'чудак',
        'урод\S*' => 'непохожий на других',
        'тварь\S*' => 'вредина',
        'жоп\S*' => 'мягкое место',
        'залуп\S*' => 'ерунда',
        'придурок\S*' => 'чудак',
        'придурк\S*' => 'чудак',
        'говн\S*' => 'ерунда',
        'дерьм\S*' => 'ерунда',
        'хер\S*' => 'ерунда',
        'нахуй' => 'куда подальше',
        'похуй' => 'всё равно',
        'заебал\S*' => 'надоел',
        'наебал\S*' => 'обманул',
        'ебан\S*' => 'странный',
    ];
}

/**
 * Заменяет грубые/матерные слова на вежливые аналоги в тексте сообщения.
 * Возвращает изменённый текст; если замен не было, возвращает исходный.
 */
function bober_moderate_text($text)
{
    $text = (string) $text;
    if ($text === '') {
        return $text;
    }

    static $compiled = null;
    if ($compiled === null) {
        $compiled = [];
        foreach (bober_moderation_word_map() as $pattern => $replacement) {
            $compiled[] = [
                'regex' => '/(?<![a-zа-яё0-9])(' . $pattern . ')(?![a-zа-яё0-9])/iu',
                'replacement' => $replacement,
            ];
        }
    }

    foreach ($compiled as $entry) {
        $text = preg_replace_callback($entry['regex'], function ($matches) use ($entry) {
            $original = $matches[1];
            $replacement = $entry['replacement'];

            // Сохраняем регистр первой буквы, чтобы "Сука" -> "Вот незадача", а не "вот незадача".
            if ($original !== '' && mb_strtoupper(mb_substr($original, 0, 1)) === mb_substr($original, 0, 1)) {
                $replacement = mb_strtoupper(mb_substr($replacement, 0, 1)) . mb_substr($replacement, 1);
            }

            return $replacement;
        }, $text);
    }

    return $text;
}
