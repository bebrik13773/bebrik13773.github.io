import { declineAdj } from './names-lib.mjs';

// Прилагательные: "слово:тип", без типа — тип y
const parse = (s) => s.trim().split(/\s+/).map((w) => { const [b, t] = w.split(':'); return declineAdj(b, t || 'y'); });
const nouns = (m, f, n) => [
    ...m.trim().split(/\s+/).filter(Boolean).map((w) => [w, 'm']),
    ...f.trim().split(/\s+/).filter(Boolean).map((w) => [w, 'f']),
    ...n.trim().split(/\s+/).filter(Boolean).map((w) => [w, 'n']),
];

