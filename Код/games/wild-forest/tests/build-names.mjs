const data = {
    version: 1,
    note: 'Словари имён из двух слов (ДЛ-15). Собирается node tests/build-names.mjs. Прилагательное: [м, ж, ср]; существительное: [слово, род m|f|n]. Менять только вместе с lib/names.php.',
    // Подстроки, которых не должно быть в готовом имени (проверяются в нижнем регистре), и запрещённые пары слов
    blacklist: ['хуй', 'хуе', 'хуя', 'пизд', 'бляд', 'блят', 'ебан', 'ебат', 'ебл', 'говн', 'жопа', 'мудак', 'мудил', 'залуп', 'сука', 'суки', 'дерьм', 'гнид', 'ссат', 'срат'],
    bad_pairs: ['Глухой Дозор', 'Кривая Плотина', 'Сонный Топор', 'Колючая Лапка', 'Рыжий Чурбан', 'Колючий Носик', 'Мохнатый Уголёк'],
    kinds: { village, character, mentor },
};
const outObj = { version: data.version, note: data.note, blacklist: data.blacklist, bad_pairs: data.bad_pairs, kinds: {} };
for (const k of Object.keys(data.kinds)) {
    outObj.kinds[k] = { adj: data.kinds[k].adj, noun: data.kinds[k].noun };
}
const line = (a) => '[\n' + a.map((x) => '      ' + JSON.stringify(x)).join(',\n') + '\n    ]';
const kinds = Object.keys(outObj.kinds).map((k) => `    "${k}": {\n    "adj": ${line(outObj.kinds[k].adj)},\n    "noun": ${line(outObj.kinds[k].noun)}\n    }`).join(',\n');
fs.writeFileSync(NAMES_PATH, `{\n  "version": 1,\n  "note": ${JSON.stringify(outObj.note)},\n  "blacklist": ${JSON.stringify(outObj.blacklist)},\n  "bad_pairs": ${JSON.stringify(outObj.bad_pairs)},\n  "kinds": {\n${kinds}\n  }\n}\n`);
for (const k of Object.keys(outObj.kinds)) console.log(k, 'прилагательных', outObj.kinds[k].adj.length, 'существительных', outObj.kinds[k].noun.length, 'сочетаний', outObj.kinds[k].adj.length * outObj.kinds[k].noun.length);
